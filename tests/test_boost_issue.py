"""End-to-end test verifying the Boost issue (/boost/boost)."""

import json
from pathlib import Path
from triage.models import IssueInput, VerificationVerdict
from triage.orchestrator import TriageOrchestrator
from triage.runner import LocalRunner, MockRunner

ROOT_DIR = Path(__file__).resolve().parent.parent


def test_boost_issue_json_files_exist_and_valid():
    paths = [
        ROOT_DIR / "issue_boost.json",
        ROOT_DIR / "examples" / "boost_issue.json",
    ]
    for p in paths:
        assert p.exists(), f"File {p} must exist"
        with open(p, "r", encoding="utf-8") as f:
            data = json.load(f)
        assert "repo_url" in data
        assert "boost" in data["repo_url"].lower()
        assert "issue" in data

        issue_obj = IssueInput.model_validate(data)
        assert "boost" in issue_obj.repo_url.lower()
        assert issue_obj.issue_title != ""


def test_boost_issue_end_to_end_triage():
    boost_json_path = ROOT_DIR / "issue_boost.json"
    with open(boost_json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    issue_input = IssueInput.model_validate(data)

    # Use local runner to execute the actual reproduction script generated by agent
    runner = LocalRunner(workdir="/tmp/triage_boost_test")
    orchestrator = TriageOrchestrator(runner=runner)

    report = orchestrator.run(issue_input)

    # Verify Clef decision
    assert report.is_ui is False, "Clef must classify Boost algorithm issue as non-UI"
    assert report.decision.playwright_needed is False
    assert report.boilerplate_id == "cpp-boost"

    # Verify Main Agent verification
    assert report.verdict == VerificationVerdict.CONFIRMED, "Boost out-of-range defect must be confirmed"
    assert report.verification is not None
    assert report.verification.reproduction_script != ""

    # Verify Fix & Architectural plan
    assert report.fix is not None
    assert report.fix.fix_applied is True, "Patch must be applied"
    assert report.fix.fixed is True, "Patch must resolve the issue and pass re-test"
    assert report.fix.pseudo_code_or_plan != ""
    assert report.fix.architectural_notes != ""
    assert report.fix.maintainer_comment != ""

    # Verify Evidence-based report structure
    md = report.to_markdown()
    assert "# Evidence-Based Issue Assessment" in md
    assert "boostorg/boost" in md or "boost" in md
    assert "## 1. Claims" in md
    assert "## 2. Evidence" in md
    assert "## 3. Verification" in md
    assert "## 4. Fix & Architectural Recommendations" in md
    assert "## 5. Uncertainty & Limitations" in md

    # Verify JSON serializability
    dumped_json = report.model_dump_json()
    assert dumped_json is not None
